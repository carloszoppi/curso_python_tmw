# Como gerar números aleatórios em Python

# %%
# Para gerar números aleatórios em Python, podemos 
# usar a biblioteca random.

import random

random.randint(1, 10) # gera um número inteiro aleatório entre 1 e 10



# %%
x = ["Teo", "Luna", "Mia", "Max", "Bella"]

random.choice(x) # escolhe aleatoriamente um elemento da lista x


